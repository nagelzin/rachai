-- Onda 7. Migração incremental; não altera despesas nem parcelas existentes.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK;
DECLARE
    n NUMBER;
    s VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
BEGIN
    IF s <> 'RACHAI' THEN RAISE_APPLICATION_ERROR(-20002, 'Selecione o schema RACHAI.'); END IF;
    SELECT COUNT(*) INTO n FROM all_tab_columns WHERE owner=s AND table_name='DESPESAS' AND column_name='TIPO_DIVISAO';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE despesas ADD tipo_divisao VARCHAR2(15 CHAR) DEFAULT ''IGUAL'' NOT NULL'; END IF;
    SELECT COUNT(*) INTO n FROM all_tables WHERE owner=s AND table_name='ACERTOS';
    IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE acertos (
        id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        grupo_id NUMBER(19,0) NOT NULL,
        devedor_id NUMBER(19,0) NOT NULL,
        recebedor_id NUMBER(19,0) NOT NULL,
        valor NUMBER(28,2) NOT NULL,
        status VARCHAR2(15 CHAR) NOT NULL,
        registrado_por_id NUMBER(19,0) NOT NULL,
        criado_em TIMESTAMP NOT NULL,
        cancelado_em TIMESTAMP,
        versao NUMBER(19,0) DEFAULT 0 NOT NULL,
        CONSTRAINT fk_acerto_grupo FOREIGN KEY(grupo_id) REFERENCES grupos(id),
        CONSTRAINT fk_acerto_devedor FOREIGN KEY(devedor_id,grupo_id) REFERENCES grupo_participantes(id,grupo_id),
        CONSTRAINT fk_acerto_recebedor FOREIGN KEY(recebedor_id,grupo_id) REFERENCES grupo_participantes(id,grupo_id),
        CONSTRAINT fk_acerto_registrador FOREIGN KEY(registrado_por_id) REFERENCES usuarios(id),
        CONSTRAINT ck_acerto_valor CHECK(valor > 0),
        CONSTRAINT ck_acerto_pessoas CHECK(devedor_id <> recebedor_id),
        CONSTRAINT ck_acerto_status CHECK(status IN (''PAGO'',''CANCELADO''))
    )'; END IF;
    SELECT COUNT(*) INTO n FROM all_indexes WHERE owner=s AND index_name='IDX_ACERTO_GRUPO';
    IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX idx_acerto_grupo ON acertos(grupo_id)'; END IF;
END;
/
