WHENEVER SQLERROR EXIT FAILURE ROLLBACK;
DECLARE
    n NUMBER;
    s VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
BEGIN
    IF s <> 'RACHAI' THEN RAISE_APPLICATION_ERROR(-20002, 'Selecione o schema RACHAI.'); END IF;
    SELECT COUNT(*) INTO n FROM all_constraints WHERE owner=s AND constraint_name='UK_DESPESA_ID_GRUPO';
    IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE despesas ADD CONSTRAINT uk_despesa_id_grupo UNIQUE(id,grupo_id)'; END IF;
    SELECT COUNT(*) INTO n FROM all_tables WHERE owner=s AND table_name='DESPESA_PARTICIPANTES';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE despesa_participantes (
            id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
            despesa_id NUMBER(19,0) NOT NULL,
            participante_id NUMBER(19,0) NOT NULL,
            grupo_id NUMBER(19,0) NOT NULL,
            CONSTRAINT uk_despesa_participante UNIQUE(despesa_id,participante_id),
            CONSTRAINT fk_envolvido_despesa_grupo FOREIGN KEY(despesa_id,grupo_id) REFERENCES despesas(id,grupo_id),
            CONSTRAINT fk_envolvido_membro_grupo FOREIGN KEY(participante_id,grupo_id) REFERENCES grupo_participantes(id,grupo_id)
        )';
    END IF;
    SELECT COUNT(*) INTO n FROM all_indexes WHERE owner=s AND index_name='IDX_ENVOLVIDO_MEMBRO';
    IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX idx_envolvido_membro ON despesa_participantes(participante_id,grupo_id)'; END IF;
END;
