-- Executar no schema RACHAI. Pode ser retomada após falha parcial de DDL.
-- Preserva todos os registros; contas legadas não recebem senha ou acesso automático.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK;
DECLARE
    n NUMBER;
    schema_atual VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
    PROCEDURE coluna(t VARCHAR2, c VARCHAR2, ddl VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO n FROM all_tab_columns WHERE owner=schema_atual AND table_name=t AND column_name=c;
        IF n=0 THEN EXECUTE IMMEDIATE ddl; END IF;
    END;
    PROCEDURE restricao(c VARCHAR2, ddl VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO n FROM all_constraints WHERE owner=schema_atual AND constraint_name=c;
        IF n=0 THEN EXECUTE IMMEDIATE ddl; END IF;
    END;
BEGIN
    IF schema_atual <> 'RACHAI' THEN RAISE_APPLICATION_ERROR(-20002, 'Selecione o schema RACHAI.'); END IF;
    coluna('USUARIOS','EMAIL','ALTER TABLE usuarios ADD email VARCHAR2(254 CHAR)');
    coluna('USUARIOS','SENHA_HASH','ALTER TABLE usuarios ADD senha_hash VARCHAR2(255 CHAR)');
    restricao('UK_USUARIO_EMAIL','ALTER TABLE usuarios ADD CONSTRAINT uk_usuario_email UNIQUE(email)');
    restricao('CK_USUARIO_CREDENCIAIS','ALTER TABLE usuarios ADD CONSTRAINT ck_usuario_credenciais CHECK ((email IS NULL AND senha_hash IS NULL) OR (email IS NOT NULL AND senha_hash IS NOT NULL))');
    coluna('GRUPO_PARTICIPANTES','USUARIO_ID','ALTER TABLE grupo_participantes ADD usuario_id NUMBER(19,0)');
    restricao('FK_PARTICIPANTE_USUARIO','ALTER TABLE grupo_participantes ADD CONSTRAINT fk_participante_usuario FOREIGN KEY(usuario_id) REFERENCES usuarios(id)');
    restricao('UK_PARTICIPANTE_USUARIO','ALTER TABLE grupo_participantes ADD CONSTRAINT uk_participante_usuario UNIQUE(grupo_id,usuario_id)');
    SELECT COUNT(*) INTO n FROM all_constraints WHERE owner=schema_atual AND constraint_name='UK_PARTICIPANTE_NOME';
    IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE grupo_participantes DROP CONSTRAINT uk_participante_nome'; END IF;
    SELECT COUNT(*) INTO n FROM all_tables WHERE owner=schema_atual AND table_name='CONVITES';
    IF n=0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE convites (
            id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
            grupo_id NUMBER(19,0) NOT NULL,
            destinatario_id NUMBER(19,0) NOT NULL,
            status VARCHAR2(10 CHAR) NOT NULL,
            criado_em TIMESTAMP NOT NULL,
            respondido_em TIMESTAMP,
            CONSTRAINT fk_convite_grupo FOREIGN KEY(grupo_id) REFERENCES grupos(id),
            CONSTRAINT fk_convite_destinatario FOREIGN KEY(destinatario_id) REFERENCES usuarios(id),
            CONSTRAINT uk_convite_destinatario UNIQUE(grupo_id,destinatario_id),
            CONSTRAINT ck_convite_status CHECK(status IN (''PENDENTE'',''ACEITO'',''RECUSADO''))
        )';
    END IF;
    SELECT COUNT(*) INTO n FROM all_indexes WHERE owner=schema_atual AND index_name='IDX_CONVITE_DESTINATARIO';
    IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX idx_convite_destinatario ON convites(destinatario_id,status)'; END IF;
END;
