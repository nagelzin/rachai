WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

CREATE TABLE usuarios (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(120 CHAR) NOT NULL
);

CREATE TABLE grupos (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(120 CHAR) NOT NULL,
    descricao VARCHAR2(500 CHAR),
    usuario_responsavel_id NUMBER(19,0) NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    CONSTRAINT fk_grupo_responsavel FOREIGN KEY (usuario_responsavel_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_grupo_responsavel ON grupos(usuario_responsavel_id);

CREATE TABLE grupo_participantes (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    grupo_id NUMBER(19,0) NOT NULL,
    nome VARCHAR2(120 CHAR) NOT NULL,
    nome_normalizado VARCHAR2(360 CHAR) NOT NULL,
    CONSTRAINT fk_participante_grupo FOREIGN KEY (grupo_id) REFERENCES grupos(id),
    CONSTRAINT uk_participante_nome UNIQUE (grupo_id, nome_normalizado)
);

CREATE TABLE despesas (
    id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    grupo_id NUMBER(19,0) NOT NULL,
    descricao VARCHAR2(200 CHAR) NOT NULL,
    valor_total NUMBER(12,2) NOT NULL,
    data_despesa DATE NOT NULL,
    CONSTRAINT fk_despesa_grupo FOREIGN KEY (grupo_id) REFERENCES grupos(id),
    CONSTRAINT ck_despesa_valor CHECK (valor_total > 0)
);

CREATE INDEX idx_despesa_grupo ON despesas(grupo_id);
